/**
 * Generates src/data/page-dates.json — a map of route → real last-modified date,
 * taken from git history. Runs automatically before every build (npm "prebuild").
 *
 * Why this exists: answer engines and AI search weight content freshness, and
 * dateModified in structured data is how they read it. The dates MUST be real.
 * Nothing here invents a date — if git can't tell us when a file last changed,
 * the route is simply omitted and the page ships without a date rather than
 * with a fabricated one.
 *
 * Static pages map one-to-one to a route. Dynamic route families (the twelve
 * signs, the planets, and so on) share the date of whichever changed most
 * recently: the template or the data file behind it. That is honest — those
 * pages genuinely do change together.
 *
 * The output file is committed. If a build environment does a shallow clone and
 * git history isn't available, the committed dates are kept rather than wiped.
 */
import { execFileSync } from "node:child_process";
import {
  readdirSync,
  statSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  existsSync,
} from "node:fs";
import { join, relative, sep } from "node:path";

const SRC_PAGES = "src/pages";
const OUT = "src/data/page-dates.json";

/** Dynamic route families: URL prefix → the source files that drive them. */
const DYNAMIC_FAMILIES = [
  {
    prefix: "/explore/signs/",
    files: ["src/pages/explore/signs/[slug].astro", "src/data/signs.ts"],
  },
  {
    prefix: "/explore/planets/",
    files: ["src/pages/explore/planets/[slug].astro", "src/data/planets.ts"],
  },
  {
    prefix: "/explore/houses/",
    files: ["src/pages/explore/houses/[slug].astro", "src/data/houses.ts"],
  },
  {
    prefix: "/explore/aspects/",
    files: ["src/pages/explore/aspects/[slug].astro", "src/data/aspects.ts"],
  },
  { prefix: "/readings/", files: ["src/pages/readings/[slug].astro"] },
];

function gitDate(file) {
  if (!existsSync(file)) return null;
  try {
    const out = execFileSync("git", ["log", "-1", "--format=%aI", "--", file], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    return out || null;
  } catch {
    return null; // no git, shallow clone, or file never committed
  }
}

function newest(files) {
  const dates = files.map(gitDate).filter(Boolean);
  if (!dates.length) return null;
  return dates.sort().at(-1);
}

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

/** src/pages/explore/dignities.astro → /explore/dignities/ */
function routeFor(file) {
  const rel = relative(SRC_PAGES, file).split(sep).join("/");
  if (rel.includes("[")) return null; // dynamic — handled by family prefixes
  if (!rel.endsWith(".astro")) return null; // endpoints (rss.xml.ts, llms.txt.ts)
  const bare = rel.replace(/\.astro$/, "");
  if (bare === "index") return "/";
  if (bare === "404") return null;
  if (bare.endsWith("/index")) return `/${bare.slice(0, -"/index".length)}/`;
  return `/${bare}/`;
}

const existing = existsSync(OUT)
  ? JSON.parse(readFileSync(OUT, "utf8"))
  : { exact: {}, prefix: {} };
const exact = { ...(existing.exact ?? {}) };
const prefix = { ...(existing.prefix ?? {}) };

let resolved = 0;
for (const file of walk(SRC_PAGES)) {
  const route = routeFor(file);
  if (!route) continue;
  const d = gitDate(file);
  if (d) {
    exact[route] = d;
    resolved++;
  }
}

for (const fam of DYNAMIC_FAMILIES) {
  const d = newest(fam.files);
  if (d) {
    prefix[fam.prefix] = d;
    resolved++;
  }
}

mkdirSync("src/data", { recursive: true });
const payload = {
  _comment:
    "Generated by scripts/gen-page-dates.mjs from git history. Do not hand-edit; dates must stay real.",
  exact: Object.fromEntries(Object.entries(exact).sort()),
  prefix: Object.fromEntries(Object.entries(prefix).sort()),
};
writeFileSync(OUT, JSON.stringify(payload, null, 2) + "\n");

if (resolved === 0) {
  console.warn(
    "[page-dates] git history unavailable — keeping previously committed dates. No dates were invented.",
  );
} else {
  console.log(
    `[page-dates] ${Object.keys(payload.exact).length} routes + ${Object.keys(payload.prefix).length} route families dated from git.`,
  );
}
